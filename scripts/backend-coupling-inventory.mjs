// A reproducible lexical index, not a claim of semantic analysis of embedded C.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { BuiltinFuncs } from '../compiler/builtins_precompiled.js';
import { K } from '../compiler/ir.js';
const patterns = {
  'C escape routes': /\bRawC\b|\bPorffor\.c\b|__Porffor_c\b|\brawHead\b/,
  'C types and operators': /\bctype\b|\bCT\[|\bBIN_PREC\b|\bCMP_OPS\b|\b(?:Bin|Un|Load|Store)\(/,
  'Native allocation and memory': /\b(?:mmap|mprotect|munmap|madvise|malloc|calloc|realloc|free|memcpy|memmove|memset|alloca)\s*\(/,
  'Native I/O, clocks, process, network': /\b(?:printf|fprintf|fwrite|fread|fopen|fclose|open|read|write|close|fork|execvp|waitpid|popen|system|getenv|clock_gettime|gettimeofday|localtime_r|gmtime_r|timegm|mktime|socket|poll|epoll_wait|uv_run)\s*\(|nativeFetch|uwebsockets/,
  'Exceptions, coroutines, threads and GC roots': /\b(?:setjmp|longjmp|ucontext_t|makecontext|swapcontext|__asm__|__builtin_frame_address)\b|\bpthread_\w+|\bporf_coro\w*|\bporf_gc_\w*|\bporf_promise_\w*/,
  'Native toolchain and compiler extensions': /__builtin_\w+|__attribute__|__wasi__|__TINYC__|execFileSync|execSync|spawnSync|\brawHead\b/
};
const files = execFileSync('git', ['ls-files', '--cached', '--others', '--exclude-standard', 'compiler', 'runtime', 'selfhosted'], { encoding: 'utf8' }).trim().split('\n').sort();
let out = '# Backend coupling source index\n\nGenerated by `node scripts/backend-coupling-inventory.mjs`. All tracked and non-ignored pending compiler, runtime, and selfhosted source files are scanned; comments and generator templates are intentionally retained. Entries are matching line numbers, not occurrence counts. See [the reviewed category table](backend-coupling-inventory.md) for interpretation.\n\n';
for (const [category, pattern] of Object.entries(patterns)) {
  out += `## ${category}\n\n| Source | Lines |\n| --- | --- |\n`;
  for (const file of files) {
    if (file === 'compiler/builtins_precompiled.js') continue;
    const lines = fs.readFileSync(file, 'utf8').split('\n').flatMap((line, i) => pattern.test(line) ? [i + 1] : []);
    if (lines.length) out += `| [${file}](../${file}) | ${lines.join(', ')} |\n`;
  }
  out += '\n';
}
const generated = fs.readFileSync('compiler/builtins_precompiled.js');
out += `## Compressed builtins\n\n\
\`compiler/builtins_precompiled.js\` is a generated, compressed cache of the legacy IR, including C strings. Its line index is not a reliable inventory of operations. Review the source builtins and \`compiler/precompile.js\`, then regenerate this cache when migrating a category. No cache migration is performed here.\n\nSHA-256: \`${createHash('sha256').update(generated).digest('hex')}\`.\n`;
// Decode via the existing cache API, preserving all unselected compile-time branches.
const builtins = {}; BuiltinFuncs(builtins);
const identity = x => x;
const hooks = {
  onFinalize() {}, hasBuiltin() { return false; }, includeBuiltin() {}, typeUsed() {},
  remapData: identity, remapAllocSite: identity, remapFuncIndex: identity, global() {}
};
const countRaw = tree => {
  if (!tree || typeof tree !== 'object') return 0;
  const own = Array.isArray(tree) && tree.length === 6 && tree[0] === K.RawC ? 1 : 0;
  return own + Object.values(tree).reduce((sum, child) => sum + countRaw(child), 0);
};
out += '\nDecoded cache bodies (including both compile-time branches and global initializers):\n\n| Builtin | RawC nodes |\n| --- | --- |\n';
for (const name of Object.keys(builtins).sort()) {
  const entry = builtins[name];
  const count = countRaw(entry.body(hooks)) + Object.values(entry.globalInits ?? {}).reduce((sum, body) => sum + countRaw(body(hooks)), 0);
  if (count) out += `| ${name} | ${count} |\n`;
}
const destination = 'docs/backend-coupling-sites.md';
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== out) throw new Error('Coupling source index is stale');
} else fs.writeFileSync(destination, out);
